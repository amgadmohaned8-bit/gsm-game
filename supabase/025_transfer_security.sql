-- ---------- the central log of the league ----------
create or replace function public.room_transfer_log(p_room uuid, p_limit int default 200)
returns table (id uuid, season text, player_id text, from_club text, to_club text, fee numeric, matchday int, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select t.id, t.season, t.player_id, t.from_club, t.to_club, t.fee, t.matchday, t.created_at
  from public.transfers t, public.rooms r
  where r.id = p_room and public.is_room_member(p_room)
    and (t.kind = 'buy' or t.to_club not in (select club_id from public.room_members where room_id = p_room))
    and t.user_id in (select user_id from public.room_members where room_id = p_room)
    and (t.league_id is null or split_part(t.league_id, '~', 1) = split_part(r.league_id, '~', 1))
  order by t.created_at desc
  limit least(p_limit, 500)
$$;
grant execute on function public.room_transfer_log(uuid, int) to authenticated;

-- ---------- a signing from the market or a computer club, inside a shared league ----------
create or replace function public.room_sign(
  p_room uuid, p_player text, p_from_club text, p_fee numeric, p_season text, p_matchday int, p_balance numeric, p_squad int
) returns void language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); mine text; owner text; lg text; human boolean;
begin
  if uid is null then raise exception 'Sign in first'; end if;
  select club_id into mine from public.room_members where room_id = p_room and user_id = uid;
  perform pg_advisory_xact_lock(hashtextextended(p_room::text || '|' || p_player, 0));
  perform set_config('gsm.deal', '1', true);
  perform public.check_buyer(p_room, coalesce(mine, ''), p_fee, p_balance, p_matchday, p_squad);
  select league_id into lg from public.rooms where id = p_room;
  select exists (select 1 from public.room_members where room_id = p_room and club_id = p_from_club) into human;
  if human then raise exception 'That club is run by a manager: send an offer'; end if;
  -- a player somebody in this league already moved is not where this app thinks he is
  owner := public.room_signed_owner(p_room, p_player);
  if owner is not null and owner <> p_from_club then raise exception 'This player was just signed by another club'; end if;
  insert into public.transfers (user_id, season, player_id, from_club, to_club, fee, kind, matchday, league_id)
    values (uid, p_season, p_player, p_from_club, mine, p_fee, 'buy', p_matchday, lg);
  insert into public.room_player_owner (room_id, player_id, club_id, user_id, updated_at)
    values (p_room, p_player, mine, uid, now())
    on conflict (room_id, player_id) do update set club_id = excluded.club_id, user_id = excluded.user_id, updated_at = now();
  update public.manager_listings set status = 'withdrawn' where room_id = p_room and player_id = p_player and status = 'open';
end $$;
grant execute on function public.room_sign(uuid, text, text, numeric, text, int, numeric, int) to authenticated;


-- ---------- the transfers table itself is guarded ----------
-- In a shared league a signing can only come from the functions above (they set a flag for the
-- length of one transaction). A sale written by the app must be of a player the seller really owns.
create or replace function public.transfers_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if coalesce(current_setting('gsm.deal', true), '') = '1' then return new; end if;
  for r in
    select rm.room_id from public.room_members rm join public.rooms ro on ro.id = rm.room_id
    where rm.user_id = new.user_id
      and (new.league_id is null or split_part(ro.league_id, '~', 1) = split_part(new.league_id, '~', 1))
  loop
    if new.kind = 'buy' then raise exception 'In a shared league, signings go through the transfer market'; end if;
    if public.room_owner(r.room_id, new.player_id) <> new.from_club then
      raise exception 'He is not at your club any more';
    end if;
  end loop;
  return new;
end $$;
drop trigger if exists transfers_guard_trg on public.transfers;
create trigger transfers_guard_trg before insert on public.transfers for each row execute function public.transfers_guard();

-- every recorded move updates who owns the player, and closes what is still open for him
create or replace function public.transfers_owner() returns trigger
language plpgsql security definer set search_path = public as $$
declare r record; holder uuid;
begin
  for r in
    select rm.room_id from public.room_members rm join public.rooms ro on ro.id = rm.room_id
    where rm.user_id = new.user_id
      and (new.league_id is null or split_part(ro.league_id, '~', 1) = split_part(new.league_id, '~', 1))
  loop
    if new.kind = 'buy' then holder := new.user_id;
    else select user_id into holder from public.room_members where room_id = r.room_id and club_id = new.to_club;
    end if;
    insert into public.room_player_owner (room_id, player_id, club_id, user_id, updated_at)
      values (r.room_id, new.player_id, new.to_club, holder, now())
      on conflict (room_id, player_id) do update set club_id = excluded.club_id, user_id = excluded.user_id, updated_at = now();
    update public.manager_listings set status = 'withdrawn' where room_id = r.room_id and player_id = new.player_id and status = 'open';
    update public.manager_offers set status = 'rejected', updated_at = now()
      where room_id = r.room_id and player_id = new.player_id and status in ('open', 'countered');
  end loop;
  return new;
end $$;
drop trigger if exists transfers_owner_trg on public.transfers;
create trigger transfers_owner_trg after insert on public.transfers for each row execute function public.transfers_owner();

-- a career reset deletes the deals: the owner record goes with them
create or replace function public.transfers_unowned() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  delete from public.room_player_owner where player_id = old.player_id and club_id = old.to_club
    and room_id in (select room_id from public.room_members where user_id = old.user_id);
  return old;
end $$;
drop trigger if exists transfers_unowned_trg on public.transfers;
create trigger transfers_unowned_trg after delete on public.transfers for each row execute function public.transfers_unowned();
