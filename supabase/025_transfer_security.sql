-- ---------- who owns a player now, in a shared league ----------
create table if not exists public.room_player_owner (
  room_id uuid not null references public.rooms(id) on delete cascade,
  player_id text not null,
  club_id text not null,
  user_id uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (room_id, player_id)
);
alter table public.room_player_owner enable row level security;
drop policy if exists "owner read" on public.room_player_owner;
create policy "owner read" on public.room_player_owner for select to authenticated using (public.is_room_member(room_id));
revoke insert, update, delete on public.room_player_owner from authenticated, anon;

-- who the last recorded move of a player in this room put him with (null when nobody has moved him)
create or replace function public.room_signed_owner(p_room uuid, p_player text) returns text
language plpgsql stable security definer set search_path = public as $$
declare o text; lg text;
begin
  select club_id into o from public.room_player_owner where room_id = p_room and player_id = p_player;
  if o is not null then return o; end if;
  select league_id into lg from public.rooms where id = p_room;
  select t.to_club into o from public.transfers t
    where t.player_id = p_player
      and t.user_id in (select user_id from public.room_members where room_id = p_room)
      and (t.league_id is null or split_part(t.league_id, '~', 1) = split_part(lg, '~', 1))
    order by t.created_at desc limit 1;
  return o;
end $$;

-- the club that owns a player now: the last move, else where he started the game
create or replace function public.room_owner(p_room uuid, p_player text) returns text
language plpgsql stable security definer set search_path = public as $$
declare o text;
begin
  o := public.room_signed_owner(p_room, p_player);
  if o is not null then return o; end if;
  select club_id into o from public.player_base_club where player_id = p_player;
  return coalesce(o, 'market');
end $$;

-- the window rule of the game: matchdays 1-10 and 20-26, and the off-season (0)
create or replace function public.window_open(p_matchday int) returns boolean language sql immutable as $$
  select p_matchday is null or p_matchday = 0 or p_matchday between 1 and 10 or p_matchday between 20 and 26
$$;

-- common checks for the buyer; raises a plain message when something is wrong
create or replace function public.check_buyer(p_room uuid, p_club text, p_fee numeric, p_balance numeric, p_matchday int, p_squad int)
returns void language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid();
begin
  if uid is null then raise exception 'Sign in first'; end if;
  if not exists (select 1 from public.room_members where room_id = p_room and user_id = uid and club_id = p_club) then
    raise exception 'That is not your club in this league';
  end if;
  if not public.window_open(p_matchday) then raise exception 'The transfer window is closed'; end if;
  if p_squad >= 35 then raise exception 'Your squad is full (35 players)'; end if;
  if p_fee > p_balance then raise exception 'Your club cannot afford this fee'; end if;
  if to_regclass('public.bank_loans') is not null then
    if exists (select 1 from public.bank_loans where user_id = uid and status = 'active' and stage >= 3) then
      raise exception 'The bank has banned signings until your debt is paid';
    end if;
  end if;
end $$;
revoke execute on function public.check_buyer(uuid, text, numeric, numeric, int, int) from public, anon, authenticated;

-- the one place a deal between two managers is written
create or replace function public.finish_deal(
  p_room uuid, p_player text, p_seller uuid, p_seller_club text, p_buyer uuid, p_buyer_club text,
  p_fee numeric, p_season text, p_matchday int
) returns void language plpgsql security definer set search_path = public as $$
declare lg text;
begin
  perform set_config('gsm.deal', '1', true);
  select league_id into lg from public.rooms where id = p_room;
  update public.manager_listings set status = 'sold' where room_id = p_room and player_id = p_player and status = 'open';
  insert into public.transfers (user_id, season, player_id, from_club, to_club, fee, kind, matchday, league_id)
    values (p_buyer, p_season, p_player, p_seller_club, p_buyer_club, p_fee, 'buy', p_matchday, lg);
  insert into public.transfers (user_id, season, player_id, from_club, to_club, fee, kind, matchday, league_id)
    values (p_seller, p_season, p_player, p_seller_club, p_buyer_club, p_fee, 'sell', p_matchday, lg);
  insert into public.room_player_owner (room_id, player_id, club_id, user_id, updated_at)
    values (p_room, p_player, p_buyer_club, p_buyer, now())
    on conflict (room_id, player_id) do update set club_id = excluded.club_id, user_id = excluded.user_id, updated_at = now();
  -- everything else still open for this player is over
  update public.manager_offers set status = 'rejected', updated_at = now()
    where room_id = p_room and player_id = p_player and status in ('open', 'countered');
end $$;
revoke execute on function public.finish_deal(uuid, text, uuid, text, uuid, text, numeric, text, int) from public, anon, authenticated;

-- ---------- Buy Now ----------
drop function if exists public.buy_manager_listing(uuid, text, text, text, int);
create or replace function public.buy_manager_listing(
  p_listing uuid, p_buyer_club text, p_season text, p_matchday int, p_balance numeric, p_squad int
) returns void language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); l public.manager_listings;
begin
  select * into l from public.manager_listings where id = p_listing;
  if l.id is null then raise exception 'This listing is gone'; end if;
  perform pg_advisory_xact_lock(hashtextextended(l.room_id::text || '|' || l.player_id, 0));
  select * into l from public.manager_listings where id = p_listing for update;
  if l.status <> 'open' then raise exception 'This player was just sold'; end if;
  if l.seller_id = uid then raise exception 'You cannot buy your own player'; end if;
  if not public.is_room_member(l.room_id) then raise exception 'Not in this league'; end if;
  perform public.check_buyer(l.room_id, p_buyer_club, l.asking, p_balance, p_matchday, p_squad);
  if public.room_owner(l.room_id, l.player_id) <> l.seller_club then raise exception 'The seller no longer owns this player'; end if;
  perform public.finish_deal(l.room_id, l.player_id, l.seller_id, l.seller_club, uid, p_buyer_club, l.asking, p_season, p_matchday);
end $$;
grant execute on function public.buy_manager_listing(uuid, text, text, int, numeric, int) to authenticated;

-- ---------- listing a player ----------
create or replace function public.listing_create(p_room uuid, p_player text, p_asking numeric)
returns uuid language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); club text; lid uuid;
begin
  if uid is null then raise exception 'Sign in first'; end if;
  select club_id into club from public.room_members where room_id = p_room and user_id = uid;
  if club is null then raise exception 'Not in this league'; end if;
  if p_asking is null or p_asking <= 0 then raise exception 'Set an asking price'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_room::text || '|' || p_player, 0));
  if public.room_owner(p_room, p_player) <> club then raise exception 'He is not in your squad'; end if;
  update public.manager_listings set status = 'withdrawn' where room_id = p_room and player_id = p_player and status = 'open' and seller_id = uid;
  insert into public.manager_listings (room_id, seller_id, seller_club, player_id, asking) values (p_room, uid, club, p_player, round(p_asking, 1))
    returning id into lid;
  return lid;
end $$;
grant execute on function public.listing_create(uuid, text, numeric) to authenticated;

