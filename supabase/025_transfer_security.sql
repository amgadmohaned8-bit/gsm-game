-- ---------- Make Offer ----------
alter table public.manager_offers add column if not exists buyer_balance numeric;

create or replace function public.offer_send(p_room uuid, p_player text, p_amount numeric, p_season text, p_balance numeric default null)
returns uuid language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); mine text; owner text; sid uuid; oid uuid;
begin
  if uid is null then raise exception 'Sign in first'; end if;
  select club_id into mine from public.room_members where room_id = p_room and user_id = uid;
  if mine is null then raise exception 'Not in this league'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter a price'; end if;
  owner := public.room_owner(p_room, p_player);
  if owner = mine then raise exception 'He is already your player'; end if;
  select user_id into sid from public.room_members where room_id = p_room and club_id = owner;
  if sid is null then raise exception 'That club is run by the computer: use the normal bid'; end if;
  insert into public.manager_offers (room_id, buyer_id, buyer_club, seller_id, seller_club, player_id, amount, season, buyer_balance)
    values (p_room, uid, mine, sid, owner, p_player, round(p_amount, 1), coalesce(p_season, ''), p_balance)
    returning id into oid;
  return oid;
exception when unique_violation then
  raise exception 'You already have an offer open for this player';
end $$;
grant execute on function public.offer_send(uuid, text, numeric, text, numeric) to authenticated;

-- reject, counter or withdraw: the only ways an offer changes besides accepting
create or replace function public.offer_answer(p_offer uuid, p_action text, p_counter numeric default null)
returns void language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); o public.manager_offers;
begin
  select * into o from public.manager_offers where id = p_offer;
  if o.id is null then raise exception 'Offer not found'; end if;
  perform pg_advisory_xact_lock(hashtextextended(o.room_id::text || '|' || o.player_id, 0));
  select * into o from public.manager_offers where id = p_offer for update;
  if o.status not in ('open', 'countered') then raise exception 'This offer is closed'; end if;
  if p_action = 'counter' then
    if o.status <> 'open' or o.seller_id <> uid then raise exception 'Only the seller can counter an open offer'; end if;
    if p_counter is null or p_counter <= 0 then raise exception 'Enter a counter price'; end if;
    update public.manager_offers set status = 'countered', counter = round(p_counter, 1), updated_at = now() where id = o.id;
  elsif p_action = 'reject' then
    if not ((o.status = 'open' and o.seller_id = uid) or (o.status = 'countered' and o.buyer_id = uid)) then raise exception 'It is not your turn to answer'; end if;
    update public.manager_offers set status = 'rejected', updated_at = now() where id = o.id;
  elsif p_action = 'withdraw' then
    if o.buyer_id <> uid then raise exception 'Only the buyer can withdraw an offer'; end if;
    update public.manager_offers set status = 'withdrawn', updated_at = now() where id = o.id;
  else
    raise exception 'Unknown action';
  end if;
end $$;
grant execute on function public.offer_answer(uuid, text, numeric) to authenticated;

-- ---------- accept: the seller accepts an offer, or the buyer accepts the counter price ----------
drop function if exists public.accept_manager_offer(uuid, text, int);
create or replace function public.accept_manager_offer(p_offer uuid, p_season text, p_matchday int, p_balance numeric, p_squad int)
returns void language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); o public.manager_offers; price numeric(8, 1);
begin
  select * into o from public.manager_offers where id = p_offer;
  if o.id is null then raise exception 'Offer not found'; end if;
  perform pg_advisory_xact_lock(hashtextextended(o.room_id::text || '|' || o.player_id, 0));
  select * into o from public.manager_offers where id = p_offer for update;
  if o.status = 'open' then
    if o.seller_id <> uid then raise exception 'Only the seller can accept this offer'; end if;
    price := o.amount;
  elsif o.status = 'countered' then
    if o.buyer_id <> uid then raise exception 'Only the buyer can accept the counter price'; end if;
    price := o.counter;
  else
    raise exception 'This offer is closed';
  end if;
  if public.room_owner(o.room_id, o.player_id) <> o.seller_club then raise exception 'The seller no longer owns this player'; end if;
  -- the buyer's money and squad are checked with the buyer's own figures
  if not exists (select 1 from public.room_members where room_id = o.room_id and user_id = o.buyer_id and club_id = o.buyer_club) then
    raise exception 'The buyer has left this club';
  end if;
  if uid = o.buyer_id then
    perform public.check_buyer(o.room_id, o.buyer_club, price, p_balance, p_matchday, p_squad);
  else
    if not public.window_open(p_matchday) then raise exception 'The transfer window is closed'; end if;
    -- the seller cannot see the buyer's books: use the balance the buyer had when he made the offer,
    -- less what he has signed since then
    if o.buyer_balance is not null and price > o.buyer_balance - coalesce((
         select sum(case when t.kind = 'buy' then t.fee else -t.fee end) from public.transfers t
         where t.user_id = o.buyer_id and t.created_at > o.created_at), 0) then
      raise exception 'The buying club cannot afford this fee any more';
    end if;
  end if;
  perform public.finish_deal(o.room_id, o.player_id, o.seller_id, o.seller_club, o.buyer_id, o.buyer_club, price, p_season, p_matchday);
  update public.manager_offers set status = 'accepted', updated_at = now() where id = o.id;
end $$;
grant execute on function public.accept_manager_offer(uuid, text, int, numeric, int) to authenticated;

