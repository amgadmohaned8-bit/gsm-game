/**
 * Writes supabase/025_base_squads.sql: who owns every player when the game starts.
 * The database needs it to check that a seller really owns the player he sells.
 *
 * Run from the project root:
 *   npx tsx scripts/exportBaseSquads.ts > supabase/025_base_squads.sql
 * Then run supabase/025_base_squads.sql in the Supabase SQL editor.
 * Run it again (and re-run the SQL) whenever you add players to squads.ts or market.ts.
 */

import { squads } from "../lib/football/squads";
import { marketPlayers } from "../lib/football/market";

const rows = new Map<string, { club: string; pos: string }>();

for (const [club, list] of Object.entries(squads)) {
  for (const p of list) if (!rows.has(p.id)) rows.set(p.id, { club, pos: p.position });
}
// the world market: players that belong to no club of the game
for (const p of marketPlayers) if (!rows.has(p.id)) rows.set(p.id, { club: "market", pos: p.position });

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const all = [...rows.entries()];

const out: string[] = [
  "-- Generated by scripts/exportBaseSquads.ts. Run once in the Supabase SQL editor (after 024).",
  `-- ${all.length} players`,
];
for (let i = 0; i < all.length; i += 400) {
  const chunk = all.slice(i, i + 400).map(([id, r]) => `(${q(id)}, ${q(r.club)}, ${q(r.pos)})`);
  out.push(
    "insert into public.player_base_owner (player_id, club_id, pos) values\n" +
      chunk.join(",\n") +
      "\non conflict (player_id) do update set club_id = excluded.club_id, pos = excluded.pos;"
  );
}
console.log(out.join("\n\n"));
